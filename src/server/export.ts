/**
 * Export — the verdict as a document. AC-5.2
 */
import type { CourtSession } from '@shared/types';
import { PERSONAS } from '../agents/personas';

const SEV_LABEL: Record<string, string> = {
  critical: 'CRITICAL', high: 'HIGH', medium: 'MEDIUM', low: 'LOW',
};

export function toMarkdown(s: CourtSession): string {
  const v = s.verdict;
  const lines: string[] = [];
  lines.push(`# AI Monster Courtroom — Verdict`, '');
  lines.push(`**Session:** \`${s.id}\``);
  lines.push(`**Date:** ${new Date(s.createdAt).toISOString()}`);
  lines.push(`**Status:** ${s.status}`);
  lines.push(`**Public link:** /v/${s.publicSlug}`, '');

  if (s.concept) {
    lines.push('## The Concept', '');
    lines.push(`- **Problem:** ${s.concept.problem}`);
    lines.push(`- **Solution:** ${s.concept.solution}`);
    lines.push(`- **Target market:** ${s.concept.targetMarket}`);
    lines.push(`- **Revenue model:** ${s.concept.revenueModel}`, '');
  }

  lines.push('## The Panel', '');
  for (const m of s.panel) {
    lines.push(`### ${PERSONAS[m.monsterId].emoji} ${m.monsterName} — ${m.perspective}`);
    if (m.failed) {
      lines.push(`_Did not report: ${m.error}_`, '');
      continue;
    }
    lines.push(`Severity: **${SEV_LABEL[m.overallSeverity]}** · Confidence: ${m.confidence}/100`, '');
    for (const f of m.findings) {
      lines.push(`- **[${SEV_LABEL[f.severity]}] ${f.category}** — ${f.claim}`);
      lines.push(`  - Evidence: ${f.evidence}`);
      if (f.requiresVerification) lines.push(`  - _Requires verification_`);
    }
    lines.push('');
  }

  if (s.debate.length) {
    lines.push('## The Debate', '');
    for (const r of s.debate) {
      lines.push(`### Round ${r.roundNumber}${r.consensus.reached ? ' — consensus reached' : ''}`);
      for (const rb of r.rebuttals) {
        lines.push(`- **${PERSONAS[rb.fromMonster].name} → ${PERSONAS[rb.toMonster].name}** (${rb.strength}): ${rb.rebuttal}`);
      }
      for (const u of r.consensus.unresolved) lines.push(`- _Unresolved:_ ${u}`);
      lines.push('');
    }
  }

  if (v) {
    lines.push('## The Verdict', '');
    lines.push(`## ${v.decision.toUpperCase()}`, '');
    lines.push(v.decisionRationale, '');
    if (v.deterministicFallback) {
      lines.push('> _Computed deterministically — the judge model was unavailable._', '');
    }

    lines.push('### Scorecard', '');
    lines.push('| Dimension | Score |');
    lines.push('|---|---|');
    lines.push(`| Financial viability | ${v.scorecard.financialViability}/100 |`);
    lines.push(`| Technical feasibility | ${v.scorecard.technicalFeasibility}/100 |`);
    lines.push(`| Market fit | ${v.scorecard.marketFit}/100 |`);
    lines.push(`| Risk profile (higher = safer) | ${v.scorecard.riskProfile}/100 |`);
    lines.push(`| **Overall** | **${v.scorecard.overall}/100** |`, '');

    lines.push('### Arguments For', '');
    for (const a of v.argumentsFor) lines.push(`- ${a.text} _(${PERSONAS[a.monster].name})_`);
    lines.push('', '### Arguments Against', '');
    for (const a of v.argumentsAgainst) lines.push(`- ${a.text} _(${PERSONAS[a.monster].name})_`);

    lines.push('', '### Hidden Assumptions', '');
    for (const a of v.hiddenAssumptions) {
      lines.push(`- **${a.assumption}**`);
      lines.push(`  - Risk if wrong: ${a.riskIfWrong}`);
      lines.push(`  - Test: ${a.howToTest}`);
    }

    lines.push('', '### Unanswered Questions', '');
    for (const q of v.unansweredQuestions) lines.push(`- ${q}`);

    lines.push('', '### Prioritized Improvements', '');
    lines.push('| Action | Effort | Impact | Why |');
    lines.push('|---|---|---|---|');
    for (const i of v.prioritizedImprovements) {
      lines.push(`| ${i.action} | ${i.effort} | ${i.impact} | ${i.rationale} |`);
    }

    lines.push('', '### Seven-Day Validation Plan', '');
    for (const d of v.validationPlan) {
      lines.push(`**Day ${d.day}** — ${d.action}`);
      lines.push(`- Success: ${d.successCriteria}`);
      lines.push(`- Effort: ${d.effort}`, '');
    }
  }

  lines.push('---', `_Generated by AI Monster Courtroom · Kiroween 2026_`);
  return lines.join('\n');
}

/** A compact share card, sized for social. AC-5.9 */
export function toShareCard(s: CourtSession): { title: string; subtitle: string; lines: string[] } {
  const v = s.verdict;
  return {
    title: v ? `Verdict: ${v.decision.toUpperCase()}` : 'In progress',
    subtitle: s.concept?.problem?.slice(0, 120) ?? 'No concept',
    lines: v
      ? [
          `Overall ${v.scorecard.overall}/100`,
          `${v.argumentsAgainst.length} argument(s) against`,
          `${v.prioritizedImprovements.length} improvement(s)`,
        ]
      : [],
  };
}
